import type { NatsUser } from '@agentmesh/bus/permissions';
import { MeshError } from '@agentmesh/common';
import { type CalloutKeys, renderCalloutAuth } from './nats-callout';
import { quote, renderUser } from './nats-users';

export interface NatsConfigInput {
  meshName: string;
  prefix: string;
  users: NatsUser[];
  /** No authorization block at all: local development only. */
  dev: boolean;
  /** JetStream disk budget in NATS size syntax, e.g. `5GB`. */
  maxFileStore: string;
  /** Client connections the server accepts in all (default DEFAULT_MAX_CONNECTIONS). */
  maxConnections?: number;
  /** Skip participants without an nkey (with a warning) instead of failing. */
  allowMissing: boolean;
  /**
   * Certificate and key paths as nats-server sees them. When set, every client
   * connection must use TLS — required when NATS is reachable from the internet.
   */
  tls?: { certFile: string; keyFile: string };
  /**
   * Account mode: agents connect through the hub's auth callout instead of
   * being listed; the hub and services stay static users.
   */
  authCallout?: CalloutKeys;
}

export interface NatsConfigResult {
  text: string;
  /** Participants left out because they have no nkey yet. */
  skipped: string[];
  /** Participants written into the authorization block. */
  included: string[];
}

export const DEFAULT_MAX_FILE_STORE = '5GB';
/**
 * Subscriptions per client connection. An agent holds two (its reply inbox and its session
 * subject), the hub and the bridge a handful. The cap keeps one member's connection from growing
 * nats-server's memory without bound. It lives here because nats-server ignores the limits in
 * user JWTs that an auth callout issues.
 */
export const MAX_SUBSCRIPTIONS = 100;
/**
 * Each Claude Code session is one connection and the hub and each service one or two, so a
 * team of 15 uses under 100. The cap bounds what a flood of connections takes from a 1–2 GB
 * server; the host firewall limits each source IP far below it (docs/deploy.md).
 */
export const DEFAULT_MAX_CONNECTIONS = 1024;
const SIZE_PATTERN = /^\d+(?:[KMGT]B?)?$/i;

/**
 * Server-wide limits. Subscriptions count per connection (MAX_SUBSCRIPTIONS). max_payload stays NATS's default 1MB, which the hub sizes its deliveries to (it reads the
 * server's value and clips a body that does not fit).
 */
function limitLines(maxConnections: number): string[] {
  if (!Number.isInteger(maxConnections) || maxConnections < 1) {
    throw new MeshError(
      'invalid_request',
      '--max-connections must be a whole number of at least 1 (default 1024)',
    );
  }
  return [
    '# Limits: what one client, or a flood of clients, can take from this server.',
    `max_connections: ${maxConnections}`,
    `max_subscriptions: ${MAX_SUBSCRIPTIONS}`,
    'max_payload: 1MB',
  ];
}

function withKeys(input: NatsConfigInput): {
  users: Array<NatsUser & { nkey: string }>;
  skipped: string[];
} {
  // In callout mode agents are admitted by the hub, so their keys do not belong here.
  const candidates = input.authCallout
    ? input.users.filter((u) => u.kind !== 'agent')
    : input.users;
  const users = candidates.flatMap((u) => (u.nkey ? [{ ...u, nkey: u.nkey }] : []));
  const skipped = candidates.filter((u) => !u.nkey).map((u) => u.id);
  if (skipped.length > 0 && !input.allowMissing) {
    throw new MeshError(
      'invalid_request',
      `No nkey for: ${skipped.join(', ')}. Run \`agentmesh keys add <id>\` for each, ` +
        'or pass --allow-missing to leave them out.',
    );
  }
  if (users.length === 0) {
    throw new MeshError('invalid_request', 'No participant has an nkey; nobody could connect.');
  }
  return { users, skipped };
}

/** Renders a complete nats-server config for the mesh. Pure: no IO. */
export function renderNatsConfig(input: NatsConfigInput): NatsConfigResult {
  if (!SIZE_PATTERN.test(input.maxFileStore)) {
    throw new MeshError(
      'invalid_request',
      `Invalid --max-file-store "${input.maxFileStore}" (e.g. 512MB, 5GB)`,
    );
  }
  const header = [
    `# Generated by \`agentmesh nats-config\` for mesh "${input.meshName}" (prefix "${input.prefix}").`,
    '# Do not edit by hand: regenerate after adding participants or keys, then reload',
    '# the server (`docker compose kill -s HUP nats`).',
    '',
    'port: 4222',
    'http: "127.0.0.1:8222"',
    '',
    ...limitLines(input.maxConnections ?? DEFAULT_MAX_CONNECTIONS),
    '',
    'jetstream {',
    '  store_dir: "/data/jetstream"',
    `  max_file_store: ${input.maxFileStore.toUpperCase()}`,
    '  # Pinned rather than left to the default: the JetStream API refuses malformed requests.',
    '  strict: true',
    '}',
    ...(input.tls
      ? [
          '',
          '# Every client connection must use TLS (clients upgrade automatically).',
          'tls {',
          `  cert_file: ${quote(input.tls.certFile)}`,
          `  key_file: ${quote(input.tls.keyFile)}`,
          '  timeout: 5',
          '}',
        ]
      : []),
  ];
  if (input.dev) {
    const warning = '# DEV MODE: no authentication. Never expose this server beyond localhost.';
    return { text: `${[...header, '', warning].join('\n')}\n`, skipped: [], included: [] };
  }
  const { users, skipped } = withKeys(input);
  const auth = input.authCallout
    ? renderCalloutAuth(users, input.prefix, input.authCallout)
    : [
        '',
        'authorization {',
        '  users: [',
        users.map((u) => renderUser(u, input.prefix)).join(',\n'),
        '  ]',
        '}',
      ];
  return {
    text: `${[...header, ...auth].join('\n')}\n`,
    skipped,
    included: users.map((u) => u.id),
  };
}
