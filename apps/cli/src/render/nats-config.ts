import { MeshError } from '@agentmesh/common';
import { type NatsUser, permissionsFor } from './permissions';

export interface NatsConfigInput {
  meshName: string;
  prefix: string;
  users: NatsUser[];
  /** No authorization block at all: local development only. */
  dev: boolean;
  /** JetStream disk budget in NATS size syntax, e.g. `5GB`. */
  maxFileStore: string;
  /** Skip participants without an nkey (with a warning) instead of failing. */
  allowMissing: boolean;
  /**
   * Certificate and key paths as nats-server sees them. When set, every client
   * connection must use TLS — required when NATS is reachable from the internet.
   */
  tls?: { certFile: string; keyFile: string };
}

export interface NatsConfigResult {
  text: string;
  /** Participants left out because they have no nkey yet. */
  skipped: string[];
  /** Participants written into the authorization block. */
  included: string[];
}

export const DEFAULT_MAX_FILE_STORE = '5GB';
const SIZE_PATTERN = /^\d+(?:[KMGT]B?)?$/i;

/** NATS config strings are double-quoted so `$JS…` is never read as a variable. */
const quote = (value: string): string => JSON.stringify(value);

function list(values: string[], indent: string): string {
  return `[\n${values.map((v) => `${indent}  ${quote(v)}`).join(',\n')}\n${indent}]`;
}

function renderUser(user: NatsUser & { nkey: string }, prefix: string): string {
  const perms = permissionsFor(user, prefix);
  const label = user.kind === 'hub' ? 'hub' : `${user.kind} ${user.id}`;
  return [
    `    # ${label}`,
    '    {',
    `      nkey: ${quote(user.nkey)}`,
    '      permissions: {',
    `        publish: { allow: ${list(perms.publish, '        ')} }`,
    `        subscribe: { allow: ${list(perms.subscribe, '        ')} }`,
    '      }',
    '    }',
  ].join('\n');
}

function withKeys(input: NatsConfigInput): {
  users: Array<NatsUser & { nkey: string }>;
  skipped: string[];
} {
  const users = input.users.flatMap((u) => (u.nkey ? [{ ...u, nkey: u.nkey }] : []));
  const skipped = input.users.filter((u) => !u.nkey).map((u) => u.id);
  if (skipped.length > 0 && !input.allowMissing) {
    throw new MeshError(
      'invalid_request',
      `No nkey for: ${skipped.join(', ')}. Run \`agentmesh keys add <id>\` for each, ` +
        'or pass --allow-missing to leave them out.',
    );
  }
  if (users.length === 0) {
    throw new MeshError('invalid_request', 'No participant has an nkey; nobody could connect.');
  }
  return { users, skipped };
}

/** Renders a complete nats-server config for the mesh. Pure: no IO. */
export function renderNatsConfig(input: NatsConfigInput): NatsConfigResult {
  if (!SIZE_PATTERN.test(input.maxFileStore)) {
    throw new MeshError(
      'invalid_request',
      `Invalid --max-file-store "${input.maxFileStore}" (e.g. 512MB, 5GB)`,
    );
  }
  const header = [
    `# Generated by \`agentmesh nats-config\` for mesh "${input.meshName}" (prefix "${input.prefix}").`,
    '# Do not edit by hand: regenerate after adding participants or keys, then reload',
    '# the server (`docker compose kill -s HUP nats`).',
    '',
    'port: 4222',
    'http: "127.0.0.1:8222"',
    '',
    'jetstream {',
    '  store_dir: "/data/jetstream"',
    `  max_file_store: ${input.maxFileStore.toUpperCase()}`,
    '}',
    ...(input.tls
      ? [
          '',
          '# Every client connection must use TLS (clients upgrade automatically).',
          'tls {',
          `  cert_file: ${quote(input.tls.certFile)}`,
          `  key_file: ${quote(input.tls.keyFile)}`,
          '  timeout: 5',
          '}',
        ]
      : []),
  ];
  if (input.dev) {
    const warning = '# DEV MODE: no authentication. Never expose this server beyond localhost.';
    return { text: `${[...header, '', warning].join('\n')}\n`, skipped: [], included: [] };
  }
  const { users, skipped } = withKeys(input);
  const auth = [
    '',
    'authorization {',
    '  users: [',
    users.map((u) => renderUser(u, input.prefix)).join(',\n'),
    '  ]',
    '}',
  ];
  return {
    text: `${[...header, ...auth].join('\n')}\n`,
    skipped,
    included: users.map((u) => u.id),
  };
}
